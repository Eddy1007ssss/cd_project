-- Cross-module persistence and booking hardening for TourFlow.

alter table public.attractions
  add column if not exists geofence_radius_m integer not null default 200
  check (geofence_radius_m between 25 and 2000);

-- Organization members may configure slots, but reservation totals are owned
-- exclusively by the security-definer booking functions.
revoke update on public.attraction_slots from authenticated;
grant update (starts_at, ends_at, maximum_capacity, status)
  on public.attraction_slots to authenticated;

create table public.feedback (
  id uuid primary key default gen_random_uuid(),
  tourist_id uuid not null references public.profiles (id) on delete cascade,
  booking_id uuid not null references public.bookings (id) on delete cascade,
  attraction_id uuid not null references public.attractions (id) on delete cascade,
  overall_rating integer not null check (overall_rating between 1 and 5),
  crowd_comfort integer not null check (crowd_comfort between 1 and 5),
  tags text[] not null default '{}',
  comment text not null default '' check (char_length(comment) <= 2000),
  created_at timestamptz not null default now(),
  unique (tourist_id, booking_id)
);

create type public.report_status as enum ('new', 'in_progress', 'resolved');
create type public.report_priority as enum ('low', 'medium', 'urgent');

create table public.issue_reports (
  id uuid primary key default gen_random_uuid(),
  report_code text not null unique default
    ('R-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))),
  tourist_id uuid not null references public.profiles (id) on delete cascade,
  attraction_id uuid not null references public.attractions (id) on delete cascade,
  booking_id uuid not null references public.bookings (id) on delete cascade,
  category text not null check (category in
    ('Overcrowding', 'Safety', 'Facility', 'Accessibility', 'Others')),
  location_note text not null check (char_length(trim(location_note)) between 2 and 200),
  description text not null check (char_length(trim(description)) between 5 and 2000),
  priority public.report_priority not null default 'medium',
  status public.report_status not null default 'new',
  assigned_to uuid references public.profiles (id) on delete set null,
  resolution_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create table public.report_events (
  id bigint generated by default as identity primary key,
  report_id uuid not null references public.issue_reports (id) on delete cascade,
  actor_id uuid not null references public.profiles (id),
  event_type text not null check (event_type in ('created', 'started', 'resolved')),
  note text,
  created_at timestamptz not null default now()
);

create table public.attraction_check_ins (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null unique references public.bookings (id) on delete cascade,
  tourist_id uuid not null references public.profiles (id) on delete cascade,
  attraction_id uuid not null references public.attractions (id) on delete cascade,
  checked_in_at timestamptz not null default now(),
  checked_out_at timestamptz,
  distance_m numeric(10, 2) not null check (distance_m >= 0),
  source text not null default 'geofence' check (source in ('geofence', 'staff_scan')),
  check (checked_out_at is null or checked_out_at >= checked_in_at)
);

create index issue_reports_tourist_created_idx
  on public.issue_reports (tourist_id, created_at desc);
create index issue_reports_attraction_status_idx
  on public.issue_reports (attraction_id, status, created_at desc);
create index attraction_check_ins_live_idx
  on public.attraction_check_ins (attraction_id, checked_in_at desc)
  where checked_out_at is null;

