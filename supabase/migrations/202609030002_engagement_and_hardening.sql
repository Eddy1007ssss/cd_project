create function public.prepare_feedback()
returns trigger language plpgsql security definer set search_path = '' as $$
declare selected_booking public.bookings;
begin
  select * into selected_booking from public.bookings where id = new.booking_id;
  if selected_booking.id is null or selected_booking.tourist_id <> (select auth.uid()) then
    raise exception 'BOOKING_ACCESS_DENIED';
  end if;
  if selected_booking.status <> 'completed' then raise exception 'VISIT_NOT_COMPLETED'; end if;
  new.tourist_id := selected_booking.tourist_id;
  select slot.attraction_id into new.attraction_id
  from public.attraction_slots slot where slot.id = selected_booking.slot_id;
  return new;
end;
$$;

create trigger feedback_prepare
before insert or update on public.feedback
for each row execute function public.prepare_feedback();

create function public.prepare_issue_report()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.tourist_id := (select auth.uid());
  if not exists (
    select 1 from public.bookings booking
    where booking.id = new.booking_id and booking.tourist_id = (select auth.uid())
  ) then raise exception 'BOOKING_ACCESS_DENIED'; end if;
  select slot.attraction_id into new.attraction_id
  from public.bookings booking
  join public.attraction_slots slot on slot.id = booking.slot_id
  where booking.id = new.booking_id;
  new.priority := case when new.category = 'Safety' then 'urgent'::public.report_priority
    else 'medium'::public.report_priority end;
  return new;
end;
$$;

create trigger issue_report_prepare
before insert on public.issue_reports
for each row execute function public.prepare_issue_report();

-- This trigger protects existing deployments of the original booking RPC as
-- well as fresh installations. It serializes each tourist's inserts and
-- validates both adjacent visits immediately before the booking is written.
create function public.validate_booking_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare selected_slot public.attraction_slots;
declare previous_record record;
declare next_record record;
begin
  if (select auth.uid()) is null then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended(new.tourist_id::text, 0));
  select * into selected_slot from public.attraction_slots where id = new.slot_id;
  if exists (
    select 1 from public.bookings booking
    join public.attraction_slots slot on slot.id = booking.slot_id
    where booking.tourist_id = new.tourist_id and booking.status = 'confirmed'
      and tstzrange(slot.starts_at, slot.ends_at, '[)')
        && tstzrange(selected_slot.starts_at, selected_slot.ends_at, '[)')
  ) then raise exception 'BOOKING_OVERLAP'; end if;
  select slot.ends_at, slot.attraction_id into previous_record
  from public.bookings booking
  join public.attraction_slots slot on slot.id = booking.slot_id
  where booking.tourist_id = new.tourist_id and booking.status = 'confirmed'
    and slot.ends_at <= selected_slot.starts_at
  order by slot.ends_at desc limit 1;
  if previous_record.ends_at is not null
    and extract(epoch from (selected_slot.starts_at - previous_record.ends_at)) / 60
      < public.estimated_travel_minutes(previous_record.attraction_id, selected_slot.attraction_id)
  then raise exception 'INSUFFICIENT_TRAVEL_TIME'; end if;
  select slot.starts_at, slot.attraction_id into next_record
  from public.bookings booking
  join public.attraction_slots slot on slot.id = booking.slot_id
  where booking.tourist_id = new.tourist_id and booking.status = 'confirmed'
    and slot.starts_at >= selected_slot.ends_at
  order by slot.starts_at limit 1;
  if next_record.starts_at is not null
    and extract(epoch from (next_record.starts_at - selected_slot.ends_at)) / 60
      < public.estimated_travel_minutes(selected_slot.attraction_id, next_record.attraction_id)
  then raise exception 'INSUFFICIENT_TRAVEL_TIME'; end if;
  return new;
end;
$$;

create trigger bookings_validate_insert
before insert on public.bookings
for each row execute function public.validate_booking_insert();

create function public.resolve_issue_report(target_report_id uuid, note text)
returns public.issue_reports language plpgsql security definer set search_path = '' as $$
declare selected_report public.issue_reports;
begin
  select * into selected_report from public.issue_reports
  where id = target_report_id for update;
  if selected_report.id is null then raise exception 'REPORT_NOT_FOUND'; end if;
  if not public.is_administrator() and not exists (
    select 1 from public.attractions attraction
    where attraction.id = selected_report.attraction_id
      and public.is_organization_member(attraction.organization_id)
  ) then raise exception 'REPORT_ACCESS_DENIED'; end if;
  if char_length(trim(note)) < 3 then raise exception 'RESOLUTION_NOTE_REQUIRED'; end if;
  update public.issue_reports set status = 'resolved', resolution_note = trim(note),
    assigned_to = (select auth.uid()), resolved_at = now()
  where id = target_report_id returning * into selected_report;
  insert into public.report_events (report_id, actor_id, event_type, note)
  values (target_report_id, (select auth.uid()), 'resolved', trim(note));
  return selected_report;
end;
$$;

create function public.check_in_booking(
  target_booking_id uuid, current_latitude double precision,
  current_longitude double precision
)
returns public.attraction_check_ins language plpgsql security definer set search_path = '' as $$
declare selected_booking public.bookings;
declare selected_slot public.attraction_slots;
declare selected_attraction public.attractions;
declare distance_m double precision;
declare created_check_in public.attraction_check_ins;
begin
  select * into selected_booking from public.bookings where id = target_booking_id for update;
  if selected_booking.id is null or selected_booking.tourist_id <> (select auth.uid()) then
    raise exception 'BOOKING_ACCESS_DENIED';
  end if;
  if selected_booking.status <> 'confirmed' then raise exception 'BOOKING_NOT_ACTIVE'; end if;
  select * into selected_slot from public.attraction_slots where id = selected_booking.slot_id;
  if now() not between selected_slot.starts_at - interval '2 hours' and selected_slot.ends_at then
    raise exception 'CHECK_IN_TIME_INVALID';
  end if;
  select * into selected_attraction from public.attractions
  where id = selected_slot.attraction_id;
  if selected_attraction.latitude is null or selected_attraction.longitude is null then
    raise exception 'ATTRACTION_LOCATION_MISSING';
  end if;
  distance_m := 6371000 * 2 * asin(sqrt(
    power(sin(radians(current_latitude - selected_attraction.latitude) / 2), 2) +
    cos(radians(selected_attraction.latitude)) * cos(radians(current_latitude)) *
    power(sin(radians(current_longitude - selected_attraction.longitude) / 2), 2)
  ));
  if distance_m > selected_attraction.geofence_radius_m then raise exception 'OUTSIDE_GEOFENCE'; end if;
  insert into public.attraction_check_ins
    (booking_id, tourist_id, attraction_id, distance_m)
  values (selected_booking.id, selected_booking.tourist_id,
    selected_attraction.id, distance_m)
  on conflict (booking_id) do update set distance_m = excluded.distance_m
  returning * into created_check_in;
  return created_check_in;
end;
$$;

